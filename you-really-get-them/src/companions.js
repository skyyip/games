export function equippedCompanion(data){
 const card=CARDS.find(card=>card.id===data.equippedCard);
 return card&&Array.isArray(data.cards)&&(data.cards.includes(card.id)||data.cards.includes(card.name))?{...card,kind:SKILLS[card.id].kind,skillName:SKILLS[card.id].name,quip:SKILLS[card.id].quip}:null;
}
export function createCompanionRun(data,{enabled=true,scope='guest'}={}){
 const card=enabled?equippedCompanion(data):null;
 return card?{card,scope,used:false,pauseUntil:0}:null;
}
export function useCompanion(run,{scope='guest',answered=false,settled=false,now=0,clue=''}={}){
 if(!run||run.scope!==scope||answered||settled||run.used||run.card.kind==='bonus'||(run.card.kind==='clue'&&!clue))return false;
 run.used=true;
 if(run.card.kind==='time')run.pauseUntil=now+5000;
 return true;
}
export function companionBonus(run,hp,scope='guest'){
 return hp>0&&run?.scope===scope&&run.card.kind==='bonus'?20:0;
}
