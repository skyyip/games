export function addStoryEvents(questions,faction,{enabled=true}={}){
 if(!enabled||!STORY_ARCS[faction])return [...questions];
 const classics=questions.filter(q=>q.kind==='classic'&&!q.picture);
 if(classics.length<3||!questions.some(q=>q.kind==='hybrid'))return [...questions];
 const removed=new Set(classics.slice(-2)),arc=STORY_ARCS[faction];
 const round=questions.filter(q=>!removed.has(q));
 const messageIndex=round.findIndex(q=>q.kind==='hybrid');
 round[messageIndex]={...MESSAGE_SCENES[faction]};
 round.splice(1,0,{...arc.setup,story:{id:arc.id,type:'setup'}});
 round.splice(8,0,{...arc.followUps[4],story:{id:arc.id,type:'callback'}});
 return round;
}
export function resolveStoryQuestion(q,records){
 if(q.story?.type!=='callback')return q;
 const arc=Object.values(STORY_ARCS).find(arc=>arc.id===q.story.id);
 const previous=records.find(r=>r.story?.id===q.story.id&&r.story.type==='setup');
 const choice=previous?.story.choiceIndex;
 const branch=Number.isInteger(choice)&&choice>=0&&choice<4?choice:4;
 return {...arc.followUps[branch],story:q.story,evidence:previous?{round:previous.round,question:previous.question,choice:previous.choice,timedOut:previous.timedOut}:null};
}
export function editedMessage(q,choice=null){
 const lines=[...q.message.draft];
 if(Number.isInteger(choice)&&q.message.edits[choice]){const [line,text]=q.message.edits[choice];lines[line]=text}
 return lines;
}
